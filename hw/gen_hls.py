# hw/gen_hls.py — turn one exported model (models/pool/mX.npz) into a Vitis HLS project folder.   Owner: P1
#   qmlp.cpp      the accelerator: same integer arithmetic as common/qmlp.py, weights baked in as constants
#   tb.cpp        testbench: runs the vectors and compares every score with the Python reference (bit-exact)
#   vectors.txt   inputs + expected scores (canary records + random test records)
#   run_hls.tcl   C simulation, synthesis for the Zynq-7020, IP export
# usage: python hw/gen_hls.py models/pool/m0.npz hw/hls/build/m0   [models/test_encoded.npz]
import os, sys
import numpy as np
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "common"))
from qmlp import QMLP
src, out = sys.argv[1], sys.argv[2]; test = sys.argv[3] if len(sys.argv) > 3 else "models/test_encoded.npz"
FOLD = os.environ.get("FOLD", "base")   # base = no pragmas (HLS default); fast = pipeline each output neuron, inner loop fully unrolled
m = QMLP.load(src); name = os.path.basename(src)[:-4]; os.makedirs(out, exist_ok=True)
n_in = m.layers[0]["W"].shape[1]; mid = int(name[1:]) if name[1:].isdigit() else 0
c = [f"// generated by hw/gen_hls.py from {os.path.basename(src)} — do not edit. Arithmetic = common/qmlp.py.",
     "#include \"qmlp.h\"", ""]
for i, ly in enumerate(m.layers):
    o, k = ly["W"].shape
    c.append(f"static const signed char W{i}[{o}][{k}] = {{")
    c += ["  {" + ",".join(str(int(v)) for v in row) + "}," for row in ly["W"]]
    c.append("};")
    c.append(f"static const long long B{i}[{o}] = {{" + ",".join(str(int(v)) for v in ly["b"]) + "};")
c += ["", "void qmlp(const unsigned char x[N_IN], int *score, unsigned char *attack, unsigned int *model_id) {",
      "#pragma HLS INTERFACE s_axilite port=x bundle=ctrl", "#pragma HLS INTERFACE s_axilite port=score bundle=ctrl",
      "#pragma HLS INTERFACE s_axilite port=attack bundle=ctrl", "#pragma HLS INTERFACE s_axilite port=model_id bundle=ctrl",
      "#pragma HLS INTERFACE s_axilite port=return bundle=ctrl", f"  int a0[{n_in}];",
      f"  for (int i = 0; i < {n_in}; i++) a0[i] = x[i];"]
for i, ly in enumerate(m.layers):
    o, k = ly["W"].shape
    if ly["L"] is None:
        c += [f"  long long acc = B{i}[0];", f"  for (int i = 0; i < {k}; i++) acc += W{i}[0][i] * a{i}[i];",
              "  *score = (int)acc;", f"  *attack = acc > {m.thr}LL;", f"  *model_id = {mid};", "}"]
    else:
        fast = [f"#pragma HLS ARRAY_PARTITION variable=a{i} complete", f"#pragma HLS ARRAY_PARTITION variable=W{i} complete dim=2"] if FOLD == "fast" else []
        c += fast
        c += [f"  int a{i + 1}[{o}];", f"  L{i}: for (int o = 0; o < {o}; o++) {{"] + (["#pragma HLS PIPELINE II=1"] if FOLD == "fast" else []) + [f"    long long acc = B{i}[o];",
              f"    for (int i = 0; i < {k}; i++) acc += W{i}[o][i] * a{i}[i];",
              f"    long long v = (acc * {ly['M']}LL + (1LL << {ly['SH'] - 1})) >> {ly['SH']};",
              f"    a{i + 1}[o] = v < 0 ? 0 : (v > {ly['L']} ? {ly['L']} : (int)v);", "  }"]
open(os.path.join(out, "qmlp.cpp"), "w").write("\n".join(c) + "\n")
open(os.path.join(out, "qmlp.h"), "w").write(f"#pragma once\n#define N_IN {n_in}\n#define MODEL_ID {mid}\n#define THR {m.thr}\n"
     "void qmlp(const unsigned char x[N_IN], int *score, unsigned char *attack, unsigned int *model_id);\n")
X = np.load(os.path.join(os.path.dirname(src), "canary.npz"))["X"]
if os.path.exists(test): X = np.vstack([X, np.load(test)["X"][:500]])
s = m.score(X)
with open(os.path.join(out, "vectors.txt"), "w") as f:
    for xi, si in zip(X, s): f.write(" ".join(str(int(v)) for v in xi) + f" {int(si)}\n")
open(os.path.join(out, "tb.cpp"), "w").write('''#include <cstdio>
#include "qmlp.h"
int main() {
  FILE *f = fopen("vectors.txt", "r"); if (!f) { printf("vectors.txt not found\\n"); return 2; }
  unsigned char x[N_IN]; int n = 0, bad = 0;
  while (true) {
    int v, ok = 1; for (int i = 0; i < N_IN; i++) { if (fscanf(f, "%d", &v) != 1) { ok = 0; break; } x[i] = (unsigned char)v; }
    long long want; if (!ok || fscanf(f, "%lld", &want) != 1) break;
    int score; unsigned char attack; unsigned int id; qmlp(x, &score, &attack, &id); n++;
    if (score != (int)want || attack != (want > THR) || id != MODEL_ID) { if (bad++ < 5) printf("MISMATCH vec %d: got %d want %lld\\n", n, score, want); }
  }
  printf("%d vectors, %d mismatches -> %s\\n", n, bad, bad || !n ? "FAIL" : "PASS"); return bad || !n;
}
''')
open(os.path.join(out, "run_hls.tcl"), "w").write(f'''# Vitis HLS 2024.1:   vitis-run --mode hls --tcl run_hls.tcl      (older: vitis_hls -f run_hls.tcl)
open_project -reset proj_{name}
set_top qmlp
add_files qmlp.cpp
add_files -tb tb.cpp
add_files -tb vectors.txt
open_solution -reset sol1 -flow_target vivado
set_part {{xc7z020clg400-1}}
create_clock -period 10 -name default
csim_design
csynth_design
export_design -format ip_catalog -ipname qmlp_{name}
exit
''')
print(f"{name}: {len(X)} test vectors -> {out}/  (check on any machine: cd {out} && g++ -O1 -o tb tb.cpp qmlp.cpp && ./tb)")
